function NormalizedSprite:Render(nvg)
    local props = self.props
    local imagePath = props.backgroundImage
    if not imagePath or imagePath == "" then return end

    local imgHandle = ImageCache.Get(imagePath)
    if not imgHandle or imgHandle <= 0 then return end

    local imgW, imgH = ImageCache.GetSize(imagePath)
    if imgW <= 0 or imgH <= 0 then return end

    local l = self:GetAbsoluteLayout()
    local bounds = IMAGE_BOUNDS[imagePath]
    if not bounds then
        bounds = { w = imgW, h = imgH, x1 = 0, y1 = 0, x2 = imgW, y2 = imgH }
    end

    local bboxW = math.max(1, bounds.x2 - bounds.x1)
    local bboxH = math.max(1, bounds.y2 - bounds.y1)
    local visualScale = tonumber(props.normalizedScale) or 0.92
    local scale = math.min((l.w * visualScale) / bboxW, (l.h * visualScale) / bboxH)
    local drawW = bounds.w * scale
    local drawH = bounds.h * scale
    local bboxCenterX = (bounds.x1 + bounds.x2) * 0.5 * scale
    local bboxCenterY = (bounds.y1 + bounds.y2) * 0.5 * scale
    local drawX = l.x + l.w * 0.5 - bboxCenterX
    local drawY = l.y + l.h * 0.5 - bboxCenterY

    local tint = props.imageTint
    local paint

    nvgSave(nvg)
    nvgIntersectScissor(nvg, l.x, l.y, l.w, l.h)
    if props.flipX then
        nvgTranslate(nvg, l.x + l.w * 0.5, l.y + l.h * 0.5)
        nvgScale(nvg, -1, 1)
        nvgTranslate(nvg, -(l.x + l.w * 0.5), -(l.y + l.h * 0.5))
    end

    if tint then
        paint = nvgImagePatternTinted(nvg, drawX, drawY, drawW, drawH, 0, imgHandle, nvgRGBA(tint[1], tint[2], tint[3], tint[4] or 255))
    else
        paint = nvgImagePattern(nvg, drawX, drawY, drawW, drawH, 0, imgHandle, 1)
    end

    nvgBeginPath(nvg)
    nvgRect(nvg, l.x, l.y, l.w, l.h)
    nvgFillPaint(nvg, paint)
    nvgFill(nvg)
    nvgRestore(nvg)
end

return NormalizedSprite
